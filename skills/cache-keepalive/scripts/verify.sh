#!/bin/sh
set -eu

skill_dir=$(CDPATH= cd -- "$(dirname -- "$0")/.." && pwd)
claude_bin=${CLAUDE_BIN:-claude}
if ! command -v "$claude_bin" >/dev/null 2>&1; then
  printf '%s\n' 'Claude Code is required. Set CLAUDE_BIN to an installed executable.' >&2
  exit 1
fi
claude_bin=$(command -v "$claude_bin")
tsc_bin=${TSC_BIN:-tsc}
if ! command -v "$tsc_bin" >/dev/null 2>&1; then
  printf '%s\n' 'TypeScript 5.4 or later is required. Set TSC_BIN to an installed tsc executable.' >&2
  exit 1
fi
tsc_bin=$(command -v "$tsc_bin")
tmp_dir=$(mktemp -d)
trap 'rm -rf "$tmp_dir"' EXIT HUP INT TERM
mkdir -p "$tmp_dir/home" "$tmp_dir/config"

run_claude() {
  env -i PATH="$PATH" HOME="$tmp_dir/home" \
    CLAUDE_CONFIG_DIR="$tmp_dir/config" \
    DISABLE_AUTOUPDATER=1 CLAUDE_CODE_DISABLE_NONESSENTIAL_TRAFFIC=1 \
    "$claude_bin" "$@"
}

run_claude --version
run_claude plugin validate --strict "$skill_dir/mod"
run_claude plugin test "$skill_dir/mod"

cp -R "$skill_dir/mod" "$tmp_dir/mod"
run_claude -p '/cache-ping status' --plugin-dir "$tmp_dir/mod" --output-format json > "$tmp_dir/status.json"
node -e '
const result = JSON.parse(require("node:fs").readFileSync(process.argv[1], "utf8"));
if (result.is_error || result.subtype !== "success" || result.local_command !== "custom"
  || result.num_turns !== 0 || result.duration_api_ms !== 0 || result.total_cost_usd !== 0
  || ["input_tokens", "output_tokens", "cache_read_input_tokens", "cache_creation_input_tokens"]
    .some(key => result.usage[key] !== 0)) {
  throw new Error("The native status command did not finish without inference");
}
console.log("Native status command passed with zero model turns and zero token usage");
' "$tmp_dir/status.json"
"$tsc_bin" --project "$tmp_dir/mod"
printf '%s\n' 'Type check passed against declarations generated by this Claude Code build'
